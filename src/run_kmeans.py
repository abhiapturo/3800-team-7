'''
Run K-means for every k and every seed in config.yaml

Read the shared input generated by src/preprocess.py and outputs:
    results/clusters_kmeans.csv
    results/runtime_kmeans.csv
'''

import time
from pathlib import Path
import pandas as pd
import scanpy as sc
import yaml
from sklearn.cluster import KMeans

config = yaml.safe_load(open("config.yaml"))

data_path = Path(config["data_path"])

if not data_path.exists():
    raise SystemExit(f"{data_path} NOT FOUND!!! Run preprocess.py")

adata = sc.read_h5ad(data_path)

X = adata.obsm["X_pca"][:, :config["n_pcs"]]

print(f"Loaded {adata.n_obs} cells, PCA input {X.shape}")

cluster_tables = []
timings = []

for k in config["k_values"]:
    for seed in config["seeds"]:
        start =  time.perf_counter()
        labels = KMeans(n_clusters = k,  n_init =  config["kmeans_n_init"], random_state = seed).fit_predict(X)
        runtime = time.perf_counter() - start

        cluster_tables.append(
            pd.DataFrame({
                "cell_id": adata.obs_names,
                "cluster": labels,
                "method" : "Kmeans",
                "parameter (K)": k,
                "seed": seed,
            })
        )

        timings.append({
            "method":"kmeans",
            "parameter (k)":k,
            "seed": seed,
            "runtime_s": round(runtime, 4)
        })

        print(f"k={k}: {len(config['seeds'])} seeds done")


output_dir = Path("results")

output_dir.mkdir(exist_ok= True)

clusters =  pd.concat(cluster_tables, ignore_index=True)
clusters.to_csv(output_dir/"clusters_kmeans.csv", index= False)
pd.DataFrame(timings).to_csv(output_dir/"runtime_kmeans.csv", index= False)

n_runs = len(timings)
print(f"Saved {n_runs} runs ({len(clusters)}) rows to {output_dir/'clusters_kmeans.csv'}")

print(f"Saved runtime to {output_dir/'runtime_kmeans.csv'}")