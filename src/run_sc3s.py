'''
Run SC3s for every k and every seed in config.yaml

SC3s (single-cell consensus clustering with speed, Quah & Hemberg 2022)
runs streaming K-means several times and combines the runs into one
consensus clustering. We use the official package (pip install sc3s,
https://github.com/hemberg-lab/sc3s).

Reads the shared input generated by src/preprocess.py and outputs:
    results/clusters_sc3s.csv
    results/runtime_sc3s.csv

Optional settings in config.yaml (defaults are used if they are missing):
    sc3s_n_runs: 5        # K-means realisations combined in each consensus (SC3s default)
    sc3s_d_range: null    # numbers of PCs used by SC3s; null = all n_pcs, so SC3s
                          # gets the same PCA representation as K-means and Leiden
'''

import logging
import time
from pathlib import Path

import anndata as ad
import pandas as pd
import scanpy as sc
import sc3s
import yaml

config = yaml.safe_load(open("config.yaml"))

data_path = Path(config["data_path"])

if not data_path.exists():
    raise SystemExit(f"{data_path} NOT FOUND!!! Run preprocess.py")

adata = sc.read_h5ad(data_path)

X = adata.obsm["X_pca"][:, :config["n_pcs"]]

n_runs = config.get("sc3s_n_runs", 5)
d_range = config.get("sc3s_d_range") or [config["n_pcs"]]

print(f"Loaded {adata.n_obs} cells, PCA input {X.shape}")
print(f"SC3s settings: n_runs={n_runs}, d_range={d_range}")

# SC3s prints many INFO/WARNING messages for every run; hide them (errors still show)
logging.disable(logging.WARNING)

cluster_tables = []
timings = []

for k in config["k_values"]:
    for seed in config["seeds"]:
        # small AnnData that holds only the shared PCA matrix;
        # SC3s reads obsm["X_pca"] and writes its result to obs["sc3s_<k>"]
        tmp = ad.AnnData(obs=pd.DataFrame(index=adata.obs_names.copy()),
                         obsm={"X_pca": X.copy()})

        start = time.perf_counter()
        sc3s.tl.consensus(tmp, n_clusters=[k], d_range=d_range,
                          n_runs=n_runs, random_state=seed)
        runtime = time.perf_counter() - start

        labels = tmp.obs[f"sc3s_{k}"].astype(int).to_numpy()

        cluster_tables.append(
            pd.DataFrame({
                "cell_id": adata.obs_names,
                "cluster": labels,
                "method": "SC3s",
                "parameter": k,
                "seed": seed,
            })
        )

        timings.append({
            "method": "SC3s",
            "parameter": k,
            "seed": seed,
            "runtime_seconds": round(runtime, 4)
        })

    print(f"k={k}: {len(config['seeds'])} seeds done")


output_dir = Path("results")

output_dir.mkdir(exist_ok=True)

clusters = pd.concat(cluster_tables, ignore_index=True)
clusters.to_csv(output_dir/"clusters_sc3s.csv", index=False)
pd.DataFrame(timings).to_csv(output_dir/"runtime_sc3s.csv", index=False)

n_runs_done = len(timings)
print(f"Saved {n_runs_done} runs ({len(clusters)} rows) to {output_dir/'clusters_sc3s.csv'}")

print(f"Saved runtime to {output_dir/'runtime_sc3s.csv'}")
